// Writes the assistant's answers for the final evaluation scenarios H01–H06 to answers/.
// Same code path as the web app, with no expert in the loop and no manual editing:
//   1. POST /api/tree    – Clef decides the six steps, the rules run the premise check (AFS originals only)
//   2. shared/engine.ts  – rule engine: ranked methods, open questions, what open answers can change
//   3. POST /api/report  – the language model writes the assessment from these fixed results
//   4. this script       – renders answers/<id>.md (readable) and answers/<id>.json (raw results)
//
//   npm run dev                                        # in another terminal
//   node scripts/answers.mjs                           # H01–H06 → answers/
//   node scripts/answers.mjs --set dev                 # D01–D08 → answers/dev/ (for comparison with the worked examples)
//   node scripts/answers.mjs --url https://<worker>    # against the deployed app
//
// Needs Node 22.18 or newer (it imports the TypeScript modules in shared/ directly).

import fs from 'node:fs'
import path from 'node:path'
import { DIM_BY_ID } from '../shared/dimensions.ts'
import { assess, resolveDimensions } from '../shared/engine.ts'
import { BASE_METHODS } from '../shared/knowledge.ts'
import { DECISION_STATUS_TEXT } from '../shared/report.ts'
import { buildReportInput } from '../shared/reportInput.ts'
import { TREE_NODES } from '../shared/tree.ts'
import { nodeStatus, rawFromDecisions } from '../shared/treeLogic.ts'
import { DEFAULT_SETTINGS } from '../shared/types.ts'

const args = Object.fromEntries(
  process.argv
    .slice(2)
    .map((a, i, all) => (a.startsWith('--') ? [a.slice(2), all[i + 1] && !all[i + 1].startsWith('--') ? all[i + 1] : true] : null))
    .filter(Boolean),
)
const BASE = args.url ?? 'http://localhost:5173'
const SET = args.set === 'dev' ? 'dev' : 'test'
const OUT = SET === 'dev' ? 'answers/dev' : 'answers'
const MODEL = args.model ?? 'gptoss'

const post = async (p, body) => {
  const r = await fetch(BASE + p, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) })
  const data = await r.json().catch(() => ({ error: `HTTP ${r.status}` }))
  if (!r.ok) throw new Error(data.error ?? `HTTP ${r.status}`)
  return data
}

const HOW = { customer: 'stated by the customer', expert: 'decided by an expert', suggested: 'suggestion – to be confirmed', conflict: 'conflict – customer text and AFS sources disagree', open: 'open – information missing' }
const STATUS_HOW = { decided: 'stated by the customer', suggested: 'suggestion – to be confirmed', conflict: 'conflict – to be checked', action: 'open – information missing', minor: 'open – not stated', expert: 'decided by an expert', deferred: 'left open' }

function render(c, tree, input, res, generatedAt) {
  const r = res.report
  const ev = res.evidence
  const cite = (s) =>
    (s ?? '').replace(/\[(E\d+(?:\s*,\s*E\d+)*)\]/g, (_, g) => {
      const refs = g
        .split(/\s*,\s*/)
        .map((id) => ev.find((e) => e.id === id))
        .filter(Boolean)
        .map((e) => `${e.source}${e.page ? ` ${e.page}` : ''}`)
      return refs.length ? `[${[...new Set(refs)].join('; ')}]` : ''
    })
  const list = (items, ordered = false) => items.map((t, i) => `${ordered ? `${i + 1}.` : '-'} ${cite(String(t).replace(/^(?:\d+[.)]|[-•*])\s+/, ''))}`).join('\n')
  const usedIds = new Set(
    JSON.stringify(r)
      .match(/E\d+/g)
      ?.concat(input.premises.flatMap((p) => p.evidence), input.steps.flatMap((s) => s.evidence)) ?? [],
  )
  const L = []
  L.push(`# ${c.id} · ${c.title}`)
  L.push('')
  L.push(
    `> Generated by **AFS Spectroscopy Assessment** (Team Hallucination Nation) on ${generatedAt.slice(0, 10)} – without manual editing. Decisions: ${tree.model} with the AFS rule engine, knowledge from the AFS originals S01–S04 only. Text: ${res.model}. Raw results: [${c.id}.json](${c.id}.json).`,
  )
  L.push('')
  L.push('## Customer enquiry')
  L.push('')
  L.push(`> ${c.text}`)
  L.push('')
  L.push('## Decision status')
  L.push('')
  L.push(cite(r.decisionStatus) || DECISION_STATUS_TEXT[input.decisionStatus])
  if (input.premises.length) {
    L.push('')
    L.push('## Premise check')
    L.push('')
    L.push('Assumptions in the request, checked against the AFS material:')
    L.push('')
    for (const p of [...input.premises].sort((a, b) => Number(b.severity === 'block') - Number(a.severity === 'block'))) {
      const src = p.evidence.map((id) => ev.find((e) => e.id === id)).filter(Boolean).map((e) => `${e.source}${e.page ? ` ${e.page}` : ''}`)
      L.push(`- **${p.severity === 'block' ? 'Contradicts the AFS material' : 'Needs checking'}:** ${p.text}${src.length ? ` [${src.join('; ')}]` : ''}`)
    }
  }
  if (input.openSteps.length) {
    L.push('')
    L.push(`**Provisional – ${input.openSteps.length} decision step${input.openSteps.length > 1 ? 's are' : ' is'} still open.** Everything below depends on the answers to these questions and is not final:`)
    L.push('')
    input.openSteps.forEach((o, i) => L.push(`${i + 1}. **${o.title}:** ${o.question}`))
  }
  const section = (title, body) => {
    if (!body || (Array.isArray(body) && !body.length)) return
    L.push('')
    L.push(`## ${title}`)
    L.push('')
    L.push(Array.isArray(body) ? body.join('\n') : body)
  }
  section('Process requirements and constraints stated', list(r.requirementsStated))
  section('Key unknowns', list(r.keyUnknowns))
  section('Clarification questions', list(r.clarificationQuestions, true))
  section('Recommended methods', r.recommendation.map((m) => `- **${m.method}.** ${cite(m.text)}`).join('\n'))
  if (input.openSteps.length && input.methods.some((m) => m.canChange.length)) {
    section('What the open answers can change', [
      '| Method | Can still change |',
      '|---|---|',
      ...input.methods.map((m) => `| ${m.rank ? `#${m.rank} ` : ''}${m.name} – ${m.technique}${m.status === 'conditional' ? ' (conditional)' : ''} | ${m.canChange.length ? m.canChange.join('; ') : 'Stays on the list whatever the answers are – only its rank can change.'} |`),
    ])
  }
  section('Measurement concept', cite(r.measurementConcept))
  section('Spectral range', cite(r.spectralRange))
  section('Risks, limitations and uncertainty', list(r.risks))
  section('First feasibility study', list(r.feasibilityPlan, true))
  section('Decision basis', cite(r.decisionBasis))
  section('Decision path (reasoning of the assistant)', [
    '| Step | Result | How it was decided | Customer wrote | AFS evidence |',
    '|---|---|---|---|---|',
    ...TREE_NODES.map((n) => {
      const def = DIM_BY_ID[n.id]
      const d = tree.decisions.find((x) => x.id === n.id)
      const st = nodeStatus(n.id, tree.decisions, {})
      const val = d?.value ? (def.labels[d.value]?.name ?? d.value) : '–'
      const refs = (d?.refs ?? []).map((x) => `${x.docId} p.${x.page}${x.role === 'caution' ? ' (caution)' : ''}`)
      return `| ${def.title} | ${val} | ${STATUS_HOW[st] ?? st} | ${d?.enquiryQuote ? `“${d.enquiryQuote.replace(/\|/g, '/')}”` : ''} | ${refs.join('; ')} |`
    }),
  ])
  section(
    'Sources',
    ev
      .filter((e) => usedIds.has(e.id))
      .map((e) => `- **${e.source}${e.page ? ` ${e.page}` : ''}** – ${e.text}${e.quote ? `  \n  Quoted passage: “${e.quote}”` : ''}`)
      .join('\n'),
  )
  L.push('')
  L.push('---')
  L.push('*A starting point for a feasibility test, not a final specification. No measured data, accuracies or prices are invented; acceptance targets come from the customer.*')
  L.push('')
  return L.join('\n')
}

const cases = JSON.parse(fs.readFileSync('eval/cases.json', 'utf8')).cases.filter((c) => c.split === SET)
fs.mkdirSync(OUT, { recursive: true })
const generatedAt = new Date().toISOString()
const index = []
for (const c of cases) {
  process.stdout.write(`${c.id} … decisions `)
  const tree = await post('/api/tree', { text: c.text, pipeline: 'clef', sources: 'original', fresh: true })
  const assessment = assess(resolveDimensions(rawFromDecisions(tree.decisions), {}, DEFAULT_SETTINGS), BASE_METHODS)
  const input = buildReportInput({ text: c.text, tree, assessment, overrides: {}, notes: {} })
  process.stdout.write('· assessment ')
  const res = await post('/api/report', { input, model: MODEL })
  fs.writeFileSync(path.join(OUT, `${c.id}.md`), render(c, tree, input, res, generatedAt))
  fs.writeFileSync(path.join(OUT, `${c.id}.json`), JSON.stringify({ case: c, generatedAt, tree, assessment: { decisionStatus: assessment.decisionStatus, warnings: assessment.warnings, candidates: assessment.candidates.filter((x) => x.status !== 'excluded') }, reportInput: input, report: res }, null, 2))
  index.push({ c, status: DECISION_STATUS_TEXT[assessment.decisionStatus], premises: assessment.warnings.length, open: input.openSteps.length, top: input.methods.filter((m) => m.status === 'recommended').slice(0, 2).map((m) => `${m.name} – ${m.technique}`) })
  console.log('✓')
}

const lines = [
  `# Assistant answers – ${SET === 'dev' ? 'development scenarios D01–D08' : 'final evaluation scenarios H01–H06'}`,
  '',
  `Generated ${generatedAt.slice(0, 16).replace('T', ' ')} UTC by \`node scripts/answers.mjs${SET === 'dev' ? ' --set dev' : ''}\` – the same pipeline as the web app, with no expert decisions, no manual editing and no case-specific code. Knowledge: AFS originals S01–S04 only.`,
  '',
  '| Scenario | Decision status | Premise findings | Open steps | Methods worth testing (top 2) |',
  '|---|---|---|---|---|',
  ...index.map((x) => `| [${x.c.id} · ${x.c.title}](${x.c.id}.md) | ${x.status} | ${x.premises} | ${x.open} | ${x.top.join('; ') || '–'} |`),
  '',
  'Each answer contains: process requirements and constraints, clarification questions, recommended methods with spectral range and measurement concept, reasoning with page-level sources (quoted passages listed at the end), risks and uncertainty, and a first feasibility-study plan. The `.json` files hold the raw decisions, rule results and the model output.',
  '',
]
fs.writeFileSync(path.join(OUT, 'README.md'), lines.join('\n'))
console.log(`\nWrote ${index.length} answers to ${OUT}/`)
